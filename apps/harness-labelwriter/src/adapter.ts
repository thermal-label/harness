/**
 * LabelWriter `DriverAdapter` — wires labelwriter-core into the
 * shared harness shell.
 *
 * Multi-engine model (plan-09): Twin Turbo + 450 Twin (`left` /
 * `right` roles, in-band roll-select on a single USB endpoint) and
 * 450 Duo + Duo 96 / Duo 128 (`label` / `tape` roles, two USB
 * interfaces, two protocols — `lw-450` paper + `d1-tape` tape) all
 * declare more than one `PrintEngine`. The shell renders engine tabs
 * iff `multiEngine.isMultiEngine(device)` returns true AND the device
 * declares >1 engine. Single-engine LWs (3xx/4xx/5xx) skip the tab
 * strip entirely (plan-09 hard rule: 6-LW renders identically to
 * today).
 *
 * Per-engine encoder dispatch picks the right encoder pair by
 * `engine.protocol`:
 *
 *   - `lw-450` / `lw-550` → `harness-core/labelwriter`
 *   - `d1-tape`           → `harness-core/labelmanager`
 *
 * The Twin `ESC q <addr>` roll-select prefix is generated by the
 * dispatch helper from `engine.bind.address` (LW Twin Turbo: `0x31`
 * left, `0x32` right). Single-engine devices and Duo's interface-
 * routed engines get a no-op prefix.
 */
